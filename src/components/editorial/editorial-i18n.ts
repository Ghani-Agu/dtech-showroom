export function edT(lang: EdLang, key: string): string {
  return ED_TR[lang][key] ?? ED_TR.fr[key] ?? key
}

/**
 * ROUND 19 — `edT` with `{placeholder}` interpolation.
 *
 * The brand pages render ONE template for 21 brands in 3 languages, so the
 * strings carry `{brand}` / `{lines}` / `{count}` instead of being written
 * out per brand. An unknown placeholder is left verbatim — it shows up in
 * review rather than silently rendering an empty gap.
 */
export function edTf(
  lang: EdLang,
  key: string,
  vars: Record<string, string | number>
): string {
  return edT(lang, key).replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole
  )
}

/** French number words for the families headline ("Neuf familles…"). */
const FR_NUMBERS: Record<number, string> = {
  2: 'Deux', 3: 'Trois', 4: 'Quatre', 5: 'Cinq', 6: 'Six', 7: 'Sept', 8: 'Huit',
  9: 'Neuf', 10: 'Dix', 11: 'Onze', 12: 'Douze', 13: 'Treize', 14: 'Quatorze',
  15: 'Quinze', 16: 'Seize', 17: 'Dix-sept', 18: 'Dix-huit', 19: 'Dix-neuf',
  20: 'Vingt', 21: 'Vingt et une', 22: 'Vingt-deux',
}
export function edCountWord(lang: EdLang, n: number): string {
  if (lang === 'fr') return FR_NUMBERS[n] ?? String(n)
  return String(n)
}
